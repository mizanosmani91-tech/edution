    public static function inWords(float|int $amount): string
    {
        $n = (int) round($amount);

        if ($n === 0) {
            return 'শূন্য টাকা মাত্র';
        }

        $parts = [];
        $crore = intdiv($n, 10000000);
        $n %= 10000000;
        $lakh = intdiv($n, 100000);
        $n %= 100000;
        $thousand = intdiv($n, 1000);
        $n %= 1000;
        $hundred = intdiv($n, 100);
        $rest = $n % 100;

        if ($crore > 0) $parts[] = self::$ones[$crore].' কোটি';
        if ($lakh > 0) $parts[] = self::$ones[$lakh].' লক্ষ';
        if ($thousand > 0) $parts[] = self::$ones[$thousand].' হাজার';
        if ($hundred > 0) $parts[] = self::$ones[$hundred].' শত';
        if ($rest > 0) $parts[] = self::$ones[$rest];

        return implode(' ', $parts).' টাকা মাত্র';
    }
